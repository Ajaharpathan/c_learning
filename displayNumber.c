#include<stdio.h>
int main()
{
	int number = 20;
	printf("Number is =  %d\n",number);
	float height = 5.6;
	printf("height is = %f\n", height);
	double weight = 60.349;
	printf("weight is = %lf\n", weight);
	char letter = 'D';
	printf("letter is = %c\n", letter);
    char name[] = "ajahar"; //char array datatype is non primitive
    printf("letter is = %s", name);
	return 0;
	
  
	
	
}
