#include<stdio.h>

int main()
{
	int a =10, b=5, c=10;
	//equal to
	printf("a==b : %d\n", a==b);
	printf("b==c : %d\n", b==c);
	printf("a==c : %d\n", a==c);
	
	//not equal to
	printf("a!=b : %d\n", a!=b);
	printf("b!=c : %d\n", b!=c);
	printf("a!=c : %d\n", a!=c);
	
	//greater than
	printf("a>b : %d\n", a>b);
	printf("b>c : %d\n", b>c);
	printf("a>c : %d\n", a>c);
	
	//less than
	printf("a<b : %d\n", a<b);
	printf("b<c : %d\n", b<c);
	printf("a<c : %d\n", a<c);
	
	//greater than equal to
	printf("a<=b : %d\n", a<=b);
	printf("b<=c : %d\n", b<=c);
	printf("a<=c : %d\n", a<=c);
	
	//less than equal to
	printf("a>=b : %d\n", a>=b);
	printf("b>=c : %d\n", b>=c);
	printf("a>=c : %d\n", a>=c);

	
	return 0;
	
}
